extension StringsX on BuildContext {
  /// Translate a key for the current language; falls back to English, then the key.
  String t(String key) {
    final lang = AppSettingsScope.of(this).locale.languageCode;
    return _strings[lang]?[key] ?? _strings['en']![key] ?? key;
  }

  /// [t] with `{name}` placeholders filled in: `context.tf('dOfN', {'n': 18})`.
  String tf(String key, Map<String, Object> args) =>
      args.entries.fold(t(key), (s, e) => s.replaceAll('{${e.key}}', '${e.value}'));

  bool get isSpanish => AppSettingsScope.of(this).locale.languageCode == 'es';
}
